#!/usr/bin/env python3
"""
将「裸 IP 列表」转换为 SwitchHosts / hosts 需要的格式：
    <IP> translate.googleapis.com

用法：
    python3 convert.py <输入IP文件> <输出hosts文件> [--limit N] [--domain translate.googleapis.com]

示例：
    python3 convert.py ip.txt hosts.txt --limit 60
    python3 convert.py ip.txt switchhosts.txt --domain translate.googleapis.com

说明：
- 输入文件每行一个 IP（可带空行/注释）。
- 默认对每个 IP 生成一行 "IP translate.googleapis.com"。
- --limit N 只取前 N 个（避免万一全写入 hosts 时过于臃肿，hosts 解析会逐个尝试）。
- 输出按 "IP 域名" 两列，空行分隔，可直接当 SwitchHosts 远程源内容。
"""
import argparse
import re

IP_RE = re.compile(r"^\s*([0-9]{1,3}(\.[0-9]{1,3}){3})\s*$")


def main() -> int:
    parser = argparse.ArgumentParser(description="裸 IP 列表 → hosts 格式")
    parser.add_argument("src", help="输入裸 IP 文件路径")
    parser.add_argument("dst", help="输出 hosts 文件路径")
    parser.add_argument("--limit", type=int, default=None,
                        help="最多取前 N 个 IP")
    parser.add_argument("--domain", default="translate.googleapis.com",
                        help="映射到的域名（默认 translate.googleapis.com）")
    args = parser.parse_args()

    ips: list[str] = []
    with open(args.src, "r", encoding="utf-8", errors="ignore") as f:
        for line in f:
            m = IP_RE.match(line)
            if m:
                ip = m.group(1)
                if ip not in ips:            # 去重
                    ips.append(ip)

    if args.limit is not None:
        ips = ips[: args.limit]

    lines = [f"{ip} {args.domain}" for ip in ips]
    if not lines:                             # 空输出时给个占位，避免日期/注释空文件
        lines = ["# no usable IP found"]

    header = (
        "# Generated by gtranslate-hosts/convert.py\n"
        f"# source: {args.src}\n"
        f"# domain: {args.domain}\n"
        f"# {len(ips)} addresses\n"
    )
    with open(args.dst, "w", encoding="utf-8", newline="\n") as f:
        f.write(header)
        f.write("\n".join(lines))
        f.write("\n")

    print(f"wrote {len(ips)} lines -> {args.dst}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())